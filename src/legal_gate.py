def _mentions_minor(text: str) -> bool:
    blob = (text or "").lower()
    if any(w in blob for w in _MINOR_WORDS):
        return True
    for m in re.finditer(MINOR_AGE_PATTERN, text or "", flags=re.IGNORECASE):
        tail = blob[m.end() : m.end() + 40]
        head = blob[max(0, m.start() - 40) : m.start()]
        if any(marker in tail or marker in head for marker in _NOT_AN_AGE):
            continue  # это срок/давность, а не возраст
        return True
    return False


def check_minors(text: str) -> List[str]:
    """Несовершеннолетние потерпевшие — без ФИО и опознаваемых деталей."""
    if _mentions_minor(text) and re.search(CYRILLIC_FULL_NAME_PATTERN, text or ""):
        return [
            "рядом упомянуты несовершеннолетний и имя-фамилия — проверить, "
            "что это НЕ потерпевший ребёнок с раскрытым именем"
        ]
    return []


