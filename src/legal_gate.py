def _has_personal_name(sentence: str) -> bool:
    """Есть ли в предложении опознаваемое лицо.

    Грубо: слово с заглавной буквы не в начале предложения. Топоним или
    название организации тоже сойдёт за имя — и это правильная сторона
    ошибки: лишняя строгость безопасна, пропущенное обвинение — нет.
    """
    words = re.findall(r"[А-ЯЁA-Z][а-яёa-z]+", sentence or "")
    first = re.match(r"\s*([А-ЯЁA-Z][а-яёa-z]+)", sentence or "")
    if first and words and words[0] == first.group(1):
        words = words[1:]
    return bool(words)


def _sentences(text: str) -> List[str]:
    """Грубое деление на предложения. Точность здесь не нужна — нужно лишь
    не дать оговорке из одного предложения оправдывать обвинение в другом.
    """
    # Делим и по «;» с «:»: оговорка «Суд признал Петрова виновным; Иванов
    # убил Сидорова» иначе легализовала бы вторую половину фразы, к которой
    # приговор не имеет никакого отношения.
    return [s for s in re.split(r"(?<=[.!?…;:])\s+|\n+", text or "") if s.strip()]


def check_verdict_status(text: str, case_status: str | None = None) -> List[str]:
    """Нет приговора → только «по версии следствия»/«подозреваемый».

    `case_status` — судебный статус, прочитанный из САМОГО источника
    (`src/case_status.py`). Он ничего не ослабляет там, где виновность не
    установлена: при `charged`, `suspected` и неизвестном статусе правила
    ровно те же, что были. Он меняет три вещи:

    * при `sentenced` / `convicted` / `pleaded_guilty` виновность уже
      установлена судом или признана самим человеком — требовать «по версии
      следствия» неверно, и такие утверждения пропускаются;

      ПРЕДЕЛ, о котором надо знать: разрешение действует на ВЕСЬ пост, а не
      на конкретное лицо. Гейт не умеет связывать приговор с человеком —
      для этого нужен разбор, кто в предложении подлежащее. Поэтому пост
      про осуждённого, где заодно обвиняют третье лицо («Суд признал
      Петрова виновным; Иванов убил Сидорова»), жёстко не блокируется —
      но такое предложение попадает в предупреждения, и владелец видит его
      перед публикацией. Закрывать этот зазор целиком — отдельная задача
      с привязкой утверждений к лицам;
    * при `acquitted` защита УСИЛИВАЕТСЯ: человек оправдан, и утверждение о
      его вине блокируется, даже если рядом стоит «по версии следствия»;
      кроме того, пост обязан назвать сам факт оправдания;
    * при `no_suspect` (никто не задержан, исполнитель безличен) фраза
      «неизвестные похитили артефакты» перестаёт считаться обвинением —
      клеветать здесь не на кого. Но только пока в предложении нет имени.

    ВАЖНО про область поиска оговорки: раньше квалификатор искался во ВСЁМ
    тексте, и пост «Убийца задержан. Обвиняемый доставлен в суд.» проходил —
    слово «обвиняемый» из второго предложения «оправдывало» прямое обвинение
    из первого. Теперь оговорка должна стоять В ТОМ ЖЕ предложении, где
    утверждение о виновности: юридически защищает только та формулировка,
    которая стоит рядом с утверждением, а не где-то ниже по тексту.
    """
    # Если в тексте прямо сказано, что человек ОСУЖДЁН, называть его
    # преступником законно во всём посте — приговор уже есть. Иначе гейт
    # блокировал корректные материалы: «...против серийного преступника.
    # <...> Суд признал Кариньяна виновным и приговорил к пожизненному» —
    # приговор назван, просто в другом предложении.
    normalized_all = normalize_for_checks(text)

    # Приговор, «найденный» в самом тексте поста, — это слова, которые
    # написала модель. Если источник говорит, что человек только обвиняется,
    # такие слова не должны ничего разрешать: иначе переписчик выдаёт себе
    # разрешение сам, дописав «суд признал его виновным» к обвинению.
    source_known = case_status is not None and case_status != _UNKNOWN_STATUS
    if case_status in _ESTABLISHED_STATUSES:
        convicted = True
    elif source_known:
        convicted = False
    else:
        # Статус источника неизвестен — работает прежнее правило по тексту.
        convicted = any(m in normalized_all for m in _CONVICTION_MARKERS)

    issues: List[str] = []

    # Оправданный человек — отдельный и более строгий случай. Пост о нём
    # обязан сказать, что суд его оправдал: материал, где остались одни
    # обвинения, и есть та самая клевета, от которой этот гейт написан.
    acquitted = case_status == _ACQUITTED_STATUS
    if acquitted and not any(m in normalized_all for m in _ACQUITTAL_MARKERS):
        issues.append(
            "источник сообщает об ОПРАВДАНИИ, а в тексте поста этого нет. "
            "Пост, оставляющий одни обвинения против оправданного человека, "
            "публиковать нельзя — скажи прямо, что суд его оправдал"
        )
    for sentence in _sentences(text):
        blob = normalize_for_checks(sentence)
        hits = [kw for kw in NO_VERDICT_GUILT_WORDS if _word_starts_with(blob, kw)]
        hits += [kw for kw in NO_VERDICT_GUILT_PHRASES if kw in blob]
        if not hits:
            continue

        # Оправданный: оговорка «по версии следствия» здесь не спасает —
        # версия следствия судом отвергнута. Легально только прошедшее
        # время обвинения рядом с самим оправданием.
        if acquitted:
            if any(m in blob for m in _ACQUITTAL_MARKERS):
                continue
            issues.append(
                f"суд ОПРАВДАЛ этого человека, а предложение утверждает его "
                f"вину ({', '.join(hits[:3])}): «{sentence.strip()[:120]}». "
                f"Допустимо только «обвинялся» рядом с упоминанием оправдания"
            )
            continue

        # Оговорка о приговоре внутри текста легализует утверждение только
        # тогда, когда источник этого не опровергает. Источник сказал
        # «обвиняется» — значит, приговора нет, чего бы ни написала модель.
        if _has_verdict_qualifier(blob) and not (source_known and not convicted
                                                 and _claims_verdict(blob)):
            continue

        # Клевета возможна только в адрес ОПОЗНАВАЕМОГО лица.
        # «Мошенники выманивали деньги у жителей» — описание явления, тут
        # блокировать нечего: иначе гейт валит нормальные посты про схемы,
        # владелец его отключит, и защиты не станет вовсе.
        # «Убийца задержан», «Иванов обманул жителей» — утверждение о вине
        # конкретного человека, даже если он не назван по имени: пост-то
        # про него. Признак явления — множественное число.
        # Ярлык блокируем и без имени: «Убийца задержан» — про конкретного
        # задержанного, и это ровно та формулировка, ради которой гейт
        # написан. Ложное срабатывание на «грабитель ворвался в квартиру»
        # стоит недорого: в конвейере это уходит на перегенерацию, модель
        # перепишет на «неизвестный ворвался» — так и правильнее. Владелец
        # видит отказ, только если сам напишет ярлык руками.
        # Исполнитель назван безлично и в предложении нет имени — обвинять
        # некого. «Неизвестные похитили артефакты», «Ограбление музея за
        # четыре минуты» — нормальная журналистика, а не утверждение о
        # виновности конкретного человека. Работает только когда источник
        # подтверждает, что задержанных и обвиняемых нет.
        # Требуется ЯВНЫЙ безличный исполнитель в ЭТОМ же предложении, а не
        # просто отсутствие имени в нём. Иначе «Иванов приехал в музей. Он
        # похитил артефакты» снимало защиту: во второй фразе имени нет, а
        # речь всё равно про Иванова.
        anonymous = (
            case_status == _NO_SUSPECT_STATUS
            and any(a in blob for a in _ANONYMOUS_ACTORS)
            and not _has_personal_name(sentence)
            and not any(kw in _LABEL_ROOTS for kw in hits)
        )
        generic = _is_generic_plural(blob, hits) or convicted or anonymous
        named = not generic
        text_issue = (
            f"утверждение о виновности без оговорки о статусе дела "
            f"({', '.join(hits[:3])}) в предложении: «{sentence.strip()[:120]}». "
            f"Нужно «по версии следствия» / «подозреваемый» / «обвиняемый» "
            f"рядом с самим утверждением, либо ссылка на вступивший в силу приговор"
        )
        if named:
            issues.append(text_issue)
        else:
            issues.append("МЯГКО: " + text_issue)
    return issues


def check_language(text: str) -> List[str]:
    """Текст поста обязан быть русским.

    Весь юридический гейт написан на кириллических паттернах. Английская
    новость (а основной поток источников — англоязычный) проходила бы его
    насквозь: «Serial killer John Smith murdered five women» не ловилось
    ничем. Такой текст в русском канале — либо сбой генерации, либо
    непереписанный исходник; публиковать его нельзя в любом случае.
    """
    letters = [ch for ch in (text or "") if ch.isalpha()]
    if len(letters) < 30:
        return []
    cyrillic = sum(1 for ch in letters if "а" <= ch.lower() <= "я" or ch.lower() == "ё")
    if cyrillic / len(letters) < 0.5:
        return [
            "текст поста не на русском языке — юридические проверки на нём "
            "не работают, публикация запрещена (вероятно, сбой переписывания)"
        ]
    return []


def check_rkn_methods(text: str) -> List[str]:
    blob = normalize_for_checks(text)
    return [p for p in RKN_METHOD_PATTERNS if p in blob]


def check_source_url(url: str) -> bool:
    return bool((url or "").strip())


def check_headline(headline: str, case_status: str | None = None) -> GateResult:
    """Гейт для заголовка, который печатается НА КАРТОЧКЕ.

    Карточка уходит в канал вместе с постом, то есть текст на ней — такая же
    публикация. Но check_post работает по тексту поста и заголовок не видит:
    «Убийца пойман» на картинке прошло бы мимо всех проверок.

    Здесь применяются только те правила, которые осмысленны для двух-трёх
    слов: презумпция невиновности, несовершеннолетние, РКН-детали. Требование
    источника и проверка языка не применяются — источник стоит в тексте поста,
    а заголовок из двух слов статистикой по алфавиту не измерить.
    """
    issues: List[str] = []
    hard_fail = False

    # Заголовку требование «назови оправдание» не предъявляем: в трёх
    # словах его не разместить, а в тексте поста оно проверяется.
    verdict = [i for i in check_verdict_status(headline or "", case_status)
               if not i.startswith("источник сообщает об ОПРАВДАНИИ")]

    # «Ограбление музея за четыре минуты» — название события, а не обвинение.
    # Послабление намеренно узкое: только когда источник подтверждает, что
    # задержанных нет, и в самом заголовке нет ни имени, ни ярлыка. В трёх
    # словах проверить это надёжно можно, в тексте поста — уже нет.
    if (verdict and case_status == _NO_SUSPECT_STATUS
            and not _has_personal_name(headline or "")
            and not any(_word_starts_with(normalize_for_checks(headline or ""), r)
                        for r in _LABEL_ROOTS)):
        verdict = ["МЯГКО: " + i.replace("МЯГКО: ", "") for i in verdict]
    if verdict:
        issues.extend(
            "заголовок карточки: " + i.replace("МЯГКО: ", "") for i in verdict
        )
        if any(not i.startswith("МЯГКО: ") for i in verdict):
            hard_fail = True

    rkn = check_rkn_methods(headline or "")
    if rkn:
        issues.append(f"заголовок карточки: РКН-детали ({', '.join(rkn)})")
        hard_fail = True

    manual_only = bool(check_minors(headline or ""))
    if manual_only:
        issues.append("заголовок карточки: упомянут несовершеннолетний рядом с именем")

    return GateResult(
        passed=not hard_fail, hard_fail=hard_fail,
        manual_only=manual_only, issues=issues,
    )


def check_pre(item: NewsItem) -> GateResult:
    """Гейт ДО rewrite — работает на сырой новости (title+body+url)."""
    text = f"{item.title} {item.body}"
    issues: List[str] = []
    hard_fail = False
    manual_only = False

    if not check_source_url(item.url):
        issues.append("нет source_url — публикация запрещена (hard fail)")
        hard_fail = True

    if check_army_rf(text):
        issues.append(
            "армия РФ/госорганы РФ в негативном контексте — только ручная "
            "модерация (ст. 207.3), auto-approve запрещён"
        )
        manual_only = True

    issues.extend(f"РКН-тема (детали метода): '{p}'" for p in check_rkn_methods(text))
    if any("РКН-тема" in i for i in issues):
        hard_fail = True

    issues.extend(check_minors(text))

    passed = not hard_fail
    return GateResult(passed=passed, hard_fail=hard_fail, manual_only=manual_only, issues=issues)


def check_post(draft_text: str, source_url: str, strict_style: bool = True,
               case_status: str | None = None) -> GateResult:
    """Гейт ПОСЛЕ rewrite — работает на готовом RU-тексте поста. LLM/mock не
    доверяем: даже если check_pre прошёл, финальный текст проверяется заново
    (double-gate).
    """
    issues: List[str] = []
    hard_fail = False

    if not check_source_url(source_url):
        issues.append("нет source_url в готовом драфте — hard fail")
        hard_fail = True

    lang_issues = check_language(draft_text)
    if lang_issues:
        issues.extend(lang_issues)
        hard_fail = True

    # Слоп-лист — это РЕДАКТОРСКОЕ качество (штампы «кроме того», «стоит
    # отметить»), а не право. Раньше он давал hard_fail наравне с юридикой,
    # и правка владельца отклонялась с формулировкой «юр. гейт не пропускает:
    # slop-list: кроме того» — человек не понимал, что нарушил закон стилем.
    # Для текста, написанного человеком (strict_style=False), стоп-слова —
    # замечание. Для машинной генерации остаются жёстким отказом: там это
    # признак того, что модель скатилась в шаблон.
    slop_hits = check_slop(draft_text)
    if slop_hits:
        issues.append(f"редакторские штампы: {', '.join(slop_hits[:5])}")
        if strict_style:
            hard_fail = True

    verdict_issues = check_verdict_status(draft_text, case_status)
    if verdict_issues:
        issues.extend(i.replace("МЯГКО: ", "") for i in verdict_issues)
        # Блокируем только обвинения в адрес НАЗВАННОГО человека — там реален
        # иск по ст. 152 ГК / 128.1 УК. Обвинения «вообще» («мошенники
        # выманивали деньги») остаются предупреждением: блокировать их значит
        # валить нормальные посты про схемы, что заставит владельца
        # отключить гейт целиком — а это худший из исходов.
        if any(not i.startswith("МЯГКО: ") for i in verdict_issues):
            hard_fail = True

    rkn_hits = check_rkn_methods(draft_text)
    if rkn_hits:
        issues.append(f"РКН-детали метода в готовом тексте: {', '.join(rkn_hits)}")
        hard_fail = True

    minor_issues = check_minors(draft_text)
    if minor_issues:
        issues.extend(minor_issues)
        # Раньше это был просто текст в issues: публикация смотрела только на
        # hard_fail, и пост с именем ребёнка-потерпевшего уходил в канал без
        # единой преграды. Теперь связка «несовершеннолетний + имя» переводит
        # пост в ручной режим — владелец обязан решить осознанно.
        manual_only_minor = True
    else:
        manual_only_minor = False

    # Ст. 207.3 проверялась только в check_pre — по СЫРОЙ новости. Но в канал
    # уходит готовый текст, и он мог быть написан заново моделью или набран
    # владельцем руками через ✏️. В обоих случаях армейская тема появлялась
    # бы уже после единственной проверки и до публикации никак не всплывала.
    manual_only = check_army_rf(draft_text) or manual_only_minor
    if check_army_rf(draft_text):
        issues.append(
            "армия/госорганы РФ в негативном контексте (ст. 207.3) — "
            "публиковать только осознанно, формулировки проверить вручную"
        )

    passed = not hard_fail
    return GateResult(
        passed=passed, hard_fail=hard_fail, manual_only=manual_only, issues=issues
    )
