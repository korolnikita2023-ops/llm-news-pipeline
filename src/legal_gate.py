@dataclass
class GateResult:
    passed: bool
    hard_fail: bool = False
    manual_only: bool = False
    issues: List[str] = field(default_factory=list)

    def merge(self, other: "GateResult") -> "GateResult":
        return GateResult(
            passed=self.passed and other.passed,
            hard_fail=self.hard_fail or other.hard_fail,
            manual_only=self.manual_only or other.manual_only,
            issues=self.issues + other.issues,
        )


@lru_cache(maxsize=1)
def load_slop_list() -> List[str]:
    for path in (SLOP_LIST_PATH, LOCAL_SLOP_LIST_PATH):
        if not path.exists():
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        phrases = [
            ln.strip().lower() for ln in lines
            if ln.strip() and not ln.strip().startswith("#")
        ]
        if phrases:
            return phrases
        print(f"[legal_gate] WARNING: {path} пуст — пробую следующий источник.")
    else:
        print(
            f"[legal_gate] WARNING: слоп-лист не найден ни в {SLOP_LIST_PATH}, "
            f"ни в {LOCAL_SLOP_LIST_PATH} — использую "
            f"короткий встроенный fallback-список slop-фраз. Перед боевым "
            f"запуском проверь путь."
        )
    return _FALLBACK_SLOP


# ---------------------------------------------------------------------------
# Нормализация текста ПЕРЕД любыми проверками.
#
# Без неё любой пункт всех списков ниже обходится одним символом — проверено:
# «у-бил», «у б и л», «у.бил», «yбил» с латинской y, «у​бил» с невидимым
# разделителем проходили гейт насквозь. Это не теоретическая атака: так же
# выглядят обычные опечатки и переносы, которые модель иногда вставляет сама.
# ---------------------------------------------------------------------------

# Латинские буквы, визуально неотличимые от кириллических.
_HOMOGLYPHS = str.maketrans({
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "x": "х", "y": "у",
    "k": "к", "h": "н", "m": "м", "t": "т", "b": "ь", "n": "п",
    "A": "А", "E": "Е", "O": "О", "P": "Р", "C": "С", "X": "Х", "Y": "У",
    "K": "К", "H": "Н", "M": "М", "T": "Т", "B": "В", "N": "П",
})

_ZERO_WIDTH = dict.fromkeys(map(ord, "​‌‍⁠﻿­"))

# Дефисы и точки внутри слова: «у-бил», «у.бил».
_INWORD_PUNCT = re.compile(r"(?<=[а-яё])[-.·‐‑‒–—]+(?=[а-яё])")
# Цепочка одиночных букв через пробел: «у б и л». Схлопываем ТОЛЬКО такие
# цепочки — если убирать все пробелы подряд, «ему билет» превратится в
# «емубилет» и даст ложное срабатывание на «убил».
_LETTER_CHAIN = re.compile(r"(?<![а-яё])(?:[а-яё][ \t]+){2,}[а-яё](?![а-яё])")


@lru_cache(maxsize=2048)
def normalize_for_checks(text: str) -> str:
    """Приводит текст к виду, на котором словарные проверки имеют смысл.

    ВАЖНО: результат используется ТОЛЬКО для проверок. Публикуется всегда
    оригинальный текст — нормализация ничего не переписывает у владельца.
    """
    if not text:
        return ""
    out = unicodedata.normalize("NFKC", text)
    out = out.translate(_ZERO_WIDTH)
    out = out.translate(_HOMOGLYPHS)
    out = out.lower()
    # Склеиваем разбитые слова, сохраняя границы соседних слов: результат
    # остаётся нормальным текстом, поэтому проверка «слово начинается с
    # корня» продолжает работать (склейка ВСЕГО текста её ломала — «убил»
    # оказывался в середине «ершовубилжену» и не находился).
    out = _INWORD_PUNCT.sub("", out)
    out = _LETTER_CHAIN.sub(lambda m: m.group(0).replace(" ", "").replace("\t", ""), out)
    return out


def check_slop(text: str) -> List[str]:
    blob = normalize_for_checks(text)
    hits = [phrase for phrase in load_slop_list() if phrase and phrase in blob]
    return hits


