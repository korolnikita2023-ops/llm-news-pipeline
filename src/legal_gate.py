def check_army_rf(text: str) -> bool:
    """Армия РФ / госорганы РФ в негативном контексте → manual-only (ст. 207.3)."""
    blob = normalize_for_checks(text)
    has_negative = any(kw in blob for kw in NEGATIVE_CONTEXT_KEYWORDS)
    if not has_negative:
        return False

    if any(kw in blob for kw in ARMY_RF_KEYWORDS):
        return True

    # Обобщённые силовые структуры — только вместе с российским контекстом.
    if any(kw in blob for kw in _GENERIC_AUTHORITY):
        return any(m in blob for m in _RF_MARKERS)
    return False


@lru_cache(maxsize=512)
def _root_re(root: str):
    """Регулярка «слово начинается с этого корня»."""
    return re.compile(r"(?<![а-яёa-z])" + re.escape(root), flags=re.IGNORECASE)


def _word_starts_with(blob: str, root: str) -> bool:
    """Слово начинается с корня — и это НЕ возвратная форма.

    «Женщина отравилась угарным газом» — про себя, а не про обвинение;
    корень «отравил» матчил её и блокировал нормальную новость. Возвратные
    формы («-ся»/«-сь») означают действие над собой, обвинением не являются.
    """
    for m in _root_re(root).finditer(blob):
        word_end = m.end()
        while word_end < len(blob) and blob[word_end].isalpha():
            word_end += 1
        word = blob[m.start() : word_end]
        if word.endswith("ся") or word.endswith("сь"):
            continue
        return True
    return False


