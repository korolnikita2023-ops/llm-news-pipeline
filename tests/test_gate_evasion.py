@pytest.mark.parametrize(
    "text",
    [
        "Восьмилетнюю Настю Кузнецову нашли мёртвой в лесу.",
        "Пропавшую 12-летнюю Марию Иванову нашли живой.",
        "Тело девочки Кати Мироновой обнаружили в подвале.",
        "Мальчик Ваня Гурьев стал жертвой нападения соседа.",
        "Внучка ветерана, Софья Петрова, стала свидетельницей.",
    ],
)
def test_minor_with_name_requires_manual_review(text):
    """Связка «ребёнок + имя» обязана останавливать автоматику. Раньше это
    был текст в issues, на который публикация не смотрела вообще."""
    assert legal_gate.check_post(text, SRC).manual_only is True


def test_prison_term_is_not_a_child_age():
    assert legal_gate.check_post(
        "Сергей Иванов получил 10 лет колонии.", SRC
    ).manual_only is False


