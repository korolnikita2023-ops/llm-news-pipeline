"""Обходы юридического гейта — находки третьего ревью (27.08.2026).

Проверка №3 показала: 20 из 30 опасных текстов проходили. Гейт обходился
одним символом (дефис, пробел, латинская буква), а целые грамматические
формы — несовершенный вид, страдательный залог, причастия, отглагольные
существительные, эвфемизмы, жаргон — не были покрыты вообще.

Эти тесты фиксируют закрытые дыры. Падение здесь = дыра вернулась.
"""
from __future__ import annotations

import pytest

from src import legal_gate

SRC = "https://bbc.com/news/1"


def blocked(text: str) -> bool:
    return legal_gate.check_post(text, SRC).hard_fail


# ---------------------------------------------------------------------------
# Обход символами: раньше срабатывал в 100% случаев
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "text",
    [
        "Ершов у-бил жену молотком.",          # дефис внутри слова
        "Петров у б и л соседа.",              # разбивка пробелами
        "Кузнецов у.бил соседку.",             # точка внутри слова
        "Андрей Кузнецов yбил свою соседку.",  # латинская y вместо у
        "Мaньяк убил трёх женщин.",            # латинская a внутри слова
        "Кузнецов у​бил соседку.",        # невидимый разделитель
    ],
)
def test_character_level_evasion_is_blocked(text):
    assert blocked(text), f"обход не пойман: {text!r}"


def test_normalization_does_not_glue_normal_words():
    """Склейка не должна портить обычный текст: «ему билет» не превращается
    в «убил», иначе гейт начнёт валить всё подряд."""
    assert legal_gate.normalize_for_checks("ему билет купили") == "ему билет купили"
    assert not blocked("Ему билет купили заранее, поездка была оплачена.")


# ---------------------------------------------------------------------------
# Грамматические формы, которых не было в списках
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "text,form",
    [
        ("Сергей Петров годами насиловал падчерицу.", "несовершенный вид"),
        ("Отчим Лапшин избивал ребёнка много лет.", "несовершенный вид"),
        ("Соседка была убита Андреем Кузнецовым.", "страдательный залог"),
        ("Кузнецов, убивший соседку, скрылся из города.", "причастие"),
        ("Тюрин совершил убийство знакомого.", "отглагольное существительное"),
        ("Роман Ильин признался в убийстве трёх женщин.", "признание вины"),
        ("Депутат Мишин получил откат 12 млн.", "коррупция"),
        ("Тищенко получил взятку 5 млн.", "коррупция"),
        ("Шульман отмывал деньги через подставные фирмы.", "отмывание"),
        ("Юсупов сбил насмерть пенсионерку.", "ДТП с умыслом"),
        ("Кузнецов лишил жизни соседку.", "эвфемизм"),
        ("Смерть соседки — дело рук Андрея Кузнецова.", "атрибуция вины"),
        ("Андрей Кузнецов грохнул соседку.", "жаргон"),
    ],
)
def test_grammatical_forms_are_covered(text, form):
    assert blocked(text), f"не поймана форма «{form}»: {text!r}"


# ---------------------------------------------------------------------------
# Ложные срабатывания, которые нельзя допускать
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "text",
    [
        "Женщина отравилась угарным газом.",          # возвратная форма
        "Мужчина утопился в реке, тело нашли утром.",  # возвратная форма
        "Уровень воровства на складах вырос втрое.",   # не обвинение лица
        "В Дагестане предотвратили террористический акт.",
        "В 2025 году зарегистрировали на 8% меньше краж.",
        "Верховный суд оправдал подсудимого за недоказанностью.",
    ],
)
def test_no_false_blocks(text):
    assert not blocked(text), f"ложная блокировка: {text!r}"


# ---------------------------------------------------------------------------
# Несовершеннолетние: раньше проверка НИЧЕГО не блокировала
