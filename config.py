    def has_llm(self) -> bool:
        if self.llm_provider == "gemini":
            return bool(self.gemini_api_key)
        if self.llm_provider == "openai":
            return bool(self.openai_api_key)
        if self.llm_provider == "anthropic":
            return bool(self.anthropic_api_key)
        return False

    def model_for_tier(self, tier: str) -> str:
        """Имя модели для текущего провайдера и уровня (LLM_TIER_CHEAP/MID)."""
        if self.llm_provider == "gemini":
            return self.gemini_model_cheap if tier == LLM_TIER_CHEAP else self.gemini_model_mid
        if self.llm_provider == "openai":
            return self.openai_model_cheap if tier == LLM_TIER_CHEAP else self.openai_model_mid
        if self.llm_provider == "anthropic":
            return self.anthropic_model_mid
        raise ValueError(f"Неизвестный LLM_PROVIDER={self.llm_provider!r} (mock сюда попадать не должен).")

    def has_telegram(self) -> bool:
        return bool(self.telegram_bot_token and self.telegram_owner_chat_id)

    def is_live_publish(self) -> bool:
        return self.publish_mode == "live"

    def is_mock(self) -> bool:
        return self.llm_provider == "mock" or not self.has_llm()


