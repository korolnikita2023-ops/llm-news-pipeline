def _legacy_selection_cap(default: int) -> int:
    """Прежняя переменная MAX_SELECTIONS_PER_DAY, если она осталась в .env.

    Она делала работу обеих новых сразу. Молча её проигнорировать нельзя:
    установка с лимитом 1 получила бы новые умолчания и стала бы тратить
    вчетверо больше. Поэтому старое значение становится основой для обоих
    новых, и об этом говорится вслух.
    """
    raw = _env("MAX_SELECTIONS_PER_DAY")
    if not raw:
        return default
    try:
        value = int(raw)
    except ValueError:
        print(f"[config] MAX_SELECTIONS_PER_DAY={raw!r} — не число, беру {default}")
        return default
    print(
        f"[config] MAX_SELECTIONS_PER_DAY={value} — переменная УСТАРЕЛА и заменена "
        f"на MAX_SUCCESSFUL_SELECTIONS_PER_DAY (готовые посты) и "
        f"MAX_PREPARATION_ATTEMPTS_PER_DAY (платные попытки). Пока беру её "
        f"значение за основу: постов {value}, попыток {value * 2}. "
        f"Задайте новые переменные явно."
    )
    return value


