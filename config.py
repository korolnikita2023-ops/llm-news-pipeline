def _env(name: str, default: str = "") -> str:
    return os.environ.get(name, default).strip()


def _env_float(name: str, default: float) -> float:
    raw = _env(name, "")
    try:
        return float(raw) if raw else default
    except ValueError:
        return default


# Ниже этого floor автоматической редакции не опускается даже через .env:
# текстов с оценкой ниже 8.0 в базе нет вовсе (промежуточные генерации не
# сохраняются), то есть решать «нормальна ли зона ниже 8.0» не на чем.
# Осознанное снижение — это анализ реальных текстов той зоны, правка этой
# константы и теста-стража, а не строчка в .env (защита от опечатки вроде
# AUTO_EDITORIAL_FLOOR=1.0, которая молча уронила бы планку канала).
AUTO_FLOOR_HARD_MIN = 8.0


def _auto_floor_from_env() -> float:
    value = _env_float("AUTO_EDITORIAL_FLOOR", AUTO_FLOOR_HARD_MIN)
    if value < AUTO_FLOOR_HARD_MIN:
        print(
            f"[config] AUTO_EDITORIAL_FLOOR={value} ниже разрешённого минимума — "
            f"использую {AUTO_FLOOR_HARD_MIN}. Снижать floor можно только вместе "
            f"с AUTO_FLOOR_HARD_MIN в config.py, после анализа текстов той зоны."
        )
        return AUTO_FLOOR_HARD_MIN
    return value


def _env_int(name: str, default: int) -> int:
    raw = _env(name, "")
    try:
        return int(raw) if raw else default
    except ValueError:
        return default


def _env_bool(name: str, default: bool = False) -> bool:
    raw = _env(name, "").lower()
    if not raw:
        return default
    return raw in {"1", "true", "yes", "y", "on"}


